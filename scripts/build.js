#!/usr/bin/env node
// Prepares public/ as a self-contained static site (what Cloudflare Pages deploys):
//   public/vendor/  docx (Word writer) and pdf.js (PDF reader) browser builds
//   public/model/   the trained model + the training set used for in-browser retraining
//   public/sw.js    service worker that caches everything for offline use
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ROOT = path.join(__dirname, "..");
const PUBLIC = path.join(ROOT, "public");

const COPIES = [
  ["node_modules/docx/dist/index.iife.js", "vendor/docx.js"],
  ["node_modules/pdfjs-dist/build/pdf.min.mjs", "vendor/pdf.min.mjs"],
  ["node_modules/pdfjs-dist/build/pdf.worker.min.mjs", "vendor/pdf.worker.min.mjs"],
  ["ml/model.json", "model/model.json"],
  ["ml/training-set.json", "model/training-set.json"],
];

for (const [from, to] of COPIES) {
  const src = path.join(ROOT, from);
  if (!fs.existsSync(src)) {
    console.error(`Missing ${from}.${from.startsWith("ml/") ? " Run `npm run train` first." : " Run `npm install` first."}`);
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(path.join(PUBLIC, to)), { recursive: true });
  fs.copyFileSync(src, path.join(PUBLIC, to));
}

// Everything the app needs, for the offline cache. The cache name is a hash of the
// files, so every deploy that changes anything replaces the old cache.
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}
const assets = walk(PUBLIC)
  .map((p) => path.relative(PUBLIC, p).split(path.sep).join("/"))
  .filter((p) => p !== "sw.js" && !p.startsWith("_") && !p.endsWith(".map"))
  .sort();
const hash = crypto.createHash("sha256");
for (const a of assets) hash.update(a).update(fs.readFileSync(path.join(PUBLIC, a)));
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/build.js — do not edit.
// Caches the whole app so it keeps working offline after the first visit.
const CACHE = "prb-${version}";
const ASSETS = ${JSON.stringify(["./", ...assets.filter((a) => a !== "index.html")], null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("prb-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy));
      }
      return res;
    }).catch(() => (req.mode === "navigate" ? caches.match("./") : Response.error()))),
  );
});
`;
fs.writeFileSync(path.join(PUBLIC, "sw.js"), sw);

const size = assets.reduce((s, a) => s + fs.statSync(path.join(PUBLIC, a)).size, 0);
console.log(`Built public/ — ${assets.length} files, ${(size / 1024 / 1024).toFixed(1)} MB, cache ${version}`);
